import { feature } from "@ember/parity";
import { describe, expect, it } from "vitest";
import catalogFile from "./lucide/catalog.json?raw";
import license from "./lucide/LICENSE.txt?raw";

// ember-rust's crates/assets/overrides/lucide/ at cfeb4c2, generated from lucide-static 1.53.0.
const COPIED = {
  "catalog.json": "c5830ac284790c69e4a8b4e6cca05c6757799774612e228b09c9ff212a19663e",
  "LICENSE.txt": "b495047bd93a9b06913511076f504daba17d5bbeb3e0650f3bb53a4220329c57",
};

interface LucideIcon {
  name: string;
  label: string;
  svg: string;
}

const catalog: LucideIcon[] = JSON.parse(catalogFile);

async function sha256(text: string) {
  const digest = await crypto.subtle.digest("SHA-256", new TextEncoder().encode(text));
  return [...new Uint8Array(digest)].map((byte) => byte.toString(16).padStart(2, "0")).join("");
}

/** The protocol's room-icons.ts: the catalog's names, in its order. */
function roomIconNames(icons: LucideIcon[]) {
  return `// Generated by apps/web/src/components/icons/catalog.test.ts from ember-rust's catalog of Lucide
// icons, copied into that folder: every icon a room can have, in the catalog's order. To change it,
// update the catalog (the folder's README says how) and run
// \`pnpm --filter @ember/web exec vitest run catalog --update\`.
export const ROOM_ICON_NAMES = [
${icons.map((icon) => `  ${JSON.stringify(icon.name)},\n`).join("")}] as const;
`;
}

describe(feature("rooms.icons"), () => {
  it("is ember-rust's catalog and license, byte for byte", async () => {
    expect({ "catalog.json": await sha256(catalogFile), "LICENSE.txt": await sha256(license) }).toEqual(COPIED);
  });

  it("holds each of Lucide's 1,869 icons once, by its own name rather than an alias", () => {
    const names = catalog.map((icon) => icon.name);
    expect(names).toHaveLength(1869);
    expect(names).toEqual([...new Set(names)].sort());
    expect(names).toContain("house");
    expect(names).not.toContain("home");
  });

  // So a page can draw the catalog's own markup, as ember-rust's picker does.
  it("draws every icon from plain shapes in the text's color", () => {
    const unsafe = /<(?:script|style|image|use|foreignObject)|\bon\w+=|href=|url\(/i;
    const strays = catalog.filter(({ svg }) => !/^<svg [^>]+>.+<\/svg>$/.test(svg) || !svg.includes('stroke="currentColor"') || unsafe.test(svg));
    expect(strays.map((icon) => icon.name)).toEqual([]);
  });

  it("gives the protocol its names", async () => {
    await expect(roomIconNames(catalog)).toMatchFileSnapshot("../../../../../packages/protocol/src/room-icons.ts");
  });
});

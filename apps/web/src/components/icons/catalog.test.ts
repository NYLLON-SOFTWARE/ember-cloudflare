import { describe, expect, it } from "vitest";
import catalogFile from "./lucide/catalog.json?raw";
import license from "./lucide/LICENSE.txt?raw";
import pickerFile from "./picker/catalog.json?raw";
import { pickerIconLabel } from "./room-icon-label";

// Lucide's catalog, generated from lucide-static 1.53.0, and the picker's catalog, which adds Iconoir
// 7.12.1's icons to Lucide's, with their tags and orders, as they were copied in.
const COPIED = {
  "lucide/catalog.json": "c5830ac284790c69e4a8b4e6cca05c6757799774612e228b09c9ff212a19663e",
  "lucide/LICENSE.txt": "b495047bd93a9b06913511076f504daba17d5bbeb3e0650f3bb53a4220329c57",
  "picker/catalog.json": "fa1a484d78aeffbf5487206de7b41fa4ffec3e883915af7a17422eabbb1e2229",
};

interface LucideIcon {
  name: string;
  label: string;
  svg: string;
}

interface PickerIcon extends LucideIcon {
  roomLabel?: string;
  collection: string;
  tags: string[];
}

const catalog: LucideIcon[] = JSON.parse(catalogFile);
const picker: { icons: PickerIcon[]; roomOrder: string[]; navigationOrder: string[] } = JSON.parse(pickerFile);

async function sha256(text: string) {
  const digest = await crypto.subtle.digest("SHA-256", new TextEncoder().encode(text));
  return [...new Uint8Array(digest)].map((byte) => byte.toString(16).padStart(2, "0")).join("");
}

/** The protocol's room-icons.ts: the picker catalog's names, in its order. */
function roomIconNames(icons: PickerIcon[]) {
  return `// Generated by apps/web/src/components/icons/catalog.test.ts from the catalog of Lucide and
// Iconoir icons in that folder's picker/: every icon a room can have, in the catalog's order.
// To change it, update the catalog (the folder's README says how) and run
// \`pnpm --filter @ember/web exec vitest run catalog --update\`.
export const ROOM_ICON_NAMES = [
${icons.map((icon) => `  ${JSON.stringify(icon.name)},\n`).join("")}] as const;
`;
}

/** room-labels.ts: what the picker calls the icons it suggests for a room's purpose. */
function roomLabels(icons: PickerIcon[]) {
  return `import type { RoomIconName } from "@ember/protocol";

// Generated by catalog.test.ts from the picker's catalog in picker/: the names its room icons go by
// where they stand for a room's purpose, such as Engineering for code-xml. Run
// \`pnpm --filter @ember/web exec vitest run catalog --update\` after updating the catalog.
export const ROOM_LABELS: Partial<Record<RoomIconName, string>> = {
${icons
  .filter((icon) => icon.roomLabel)
  .map((icon) => `  ${JSON.stringify(icon.name)}: ${JSON.stringify(icon.roomLabel)},\n`)
  .join("")}};
`;
}

describe("Room icons", () => {
  it("is the catalogs and Lucide's license as they were copied in, byte for byte", async () => {
    expect({
      "lucide/catalog.json": await sha256(catalogFile),
      "lucide/LICENSE.txt": await sha256(license),
      "picker/catalog.json": await sha256(pickerFile),
    }).toEqual(COPIED);
  });

  it("holds each of Lucide's 1,869 icons once, by its own name rather than an alias", () => {
    const names = catalog.map((icon) => icon.name);
    expect(names).toHaveLength(1869);
    expect(names).toEqual([...new Set(names)].sort());
    expect(names).toContain("house");
    expect(names).not.toContain("home");
  });

  it("offers each of Lucide's icons, as Lucide's catalog draws it, and Iconoir's 1,671, each once, in order of name", () => {
    const names = picker.icons.map((icon) => icon.name);
    expect(names).toHaveLength(3540);
    expect(names).toEqual([...new Set(names)].sort());
    const lucide = picker.icons.filter((icon) => icon.collection === "Lucide");
    expect(lucide.map(({ name, label, svg }) => ({ name, label, svg }))).toEqual(catalog);
    const iconoir = picker.icons.filter((icon) => icon.collection === "Iconoir");
    expect(iconoir).toHaveLength(1671);
    expect(iconoir.filter((icon) => !/^iconoir:(regular|solid):[a-z0-9]+(-[a-z0-9]+)*$/.test(icon.name))).toEqual([]);
  });

  it("names each icon for its name's words, solid Iconoir ones so", () => {
    expect(picker.icons.filter((icon) => pickerIconLabel(icon.name as never) !== icon.label).map((icon) => icon.name)).toEqual([]);
    expect(pickerIconLabel("gamepad-2")).toBe("Gamepad 2");
    expect(pickerIconLabel("iconoir:regular:coffee-cup")).toBe("Coffee Cup");
    expect(pickerIconLabel("iconoir:solid:heart")).toBe("Heart (Solid)");
  });

  it("orders every icon once for rooms and once for navigation", () => {
    const names = picker.icons.map((icon) => icon.name);
    for (const order of [picker.roomOrder, picker.navigationOrder]) expect([...order].sort()).toEqual(names);
  });

  // So a page can draw the catalog's own markup.
  it("draws every icon from plain shapes in the text's color", () => {
    const unsafe = /<(?:script|style|image|use|foreignObject)|\bon\w+=|href=|url\(/i;
    const strays = [...catalog, ...picker.icons].filter(
      ({ svg }) => !/^<svg [^>]+>.+<\/svg>$/.test(svg) || !/(stroke|fill)="currentColor"/.test(svg) || /(stroke|fill)="(?!currentColor|none)/.test(svg) || unsafe.test(svg),
    );
    expect(strays.map((icon) => icon.name)).toEqual([]);
  });

  it("gives the protocol its names", async () => {
    await expect(roomIconNames(picker.icons)).toMatchFileSnapshot("../../../../../packages/protocol/src/room-icons.ts");
  });

  it("gives the picker the names of the icons it suggests for rooms", async () => {
    await expect(roomLabels(picker.icons)).toMatchFileSnapshot("./room-labels.ts");
  });
});

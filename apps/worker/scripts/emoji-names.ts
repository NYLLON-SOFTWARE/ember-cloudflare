// Writes src/bots/emoji-names.ts, the emoji that Slack's shortcodes name, from emoji-datasource's
// emoji.json, which lists each emoji's short names, as `:+1:` and `:thumbsup:` name 👍, and its forms in
// each skin tone, as `:+1::skin-tone-3:` gives 👍🏼:
//
//   node apps/worker/scripts/emoji-names.ts

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const VERSION = "16.0.0";
const SOURCE = `https://unpkg.com/emoji-datasource@${VERSION}/emoji.json`;

/** What emoji.json says of an emoji, as far as this needs. */
interface Emoji {
  unified: string;
  short_names: string[];
  skin_variations?: Record<string, { unified: string }>;
}

/** The skin tones' modifiers, which `:skin-tone-2:` to `:skin-tone-6:` name. */
const TONES = ["1F3FB", "1F3FC", "1F3FD", "1F3FE", "1F3FF"];

/** Code points as emoji.json writes them, `1F44D-1F3FC`, as text. */
const textOf = (unified: string) => String.fromCodePoint(...unified.split("-").map((hex) => parseInt(hex, 16)));

/**
 * `unified` with `tone` after its first code point, in place of the variation selector after it, and
 * with `twice`, after its last as well, as two people take one tone.
 */
function toned(unified: string, tone: string, twice: boolean): string {
  const [first, ...rest] = unified.split("-");
  if (rest[0] === "FE0F") rest.shift();
  return [first, tone, ...rest, ...(twice ? [tone] : [])].join("-");
}

/**
 * Where a skin tone goes in `emoji`, as `toned` puts it: 1 for after its first code point, 2 for its
 * last as well, or null for an emoji without skin tones. Throws for one whose tones are neither, which a
 * new emoji.json would need this to learn.
 */
function toneRuleOf({ unified, short_names, skin_variations }: Emoji): 1 | 2 | null {
  if (!skin_variations) return null;
  for (const rule of [1, 2] as const) {
    // A tone for two people is the same tone for each, as `1F3FB-1F3FB`.
    const tonedAs = (tone: string) => (skin_variations[tone] ?? skin_variations[`${tone}-${tone}`])?.unified;
    if (TONES.every((tone) => tonedAs(tone) === toned(unified, tone, rule === 2))) return rule;
  }
  throw new Error(`Skin tones of :${short_names[0]}: follow no rule`);
}

const response = await fetch(SOURCE);
if (!response.ok) throw new Error(`${SOURCE} answered ${response.status}`);
const emoji = (await response.json()) as Emoji[];

const names = emoji.flatMap((entry) => entry.short_names.map((name) => ({ name, text: textOf(entry.unified), rule: toneRuleOf(entry) })));
names.sort((a, b) => (a.name < b.name ? -1 : 1));
const toneNames = names.filter(({ rule }) => rule !== null);

const output = `// Generated by apps/worker/scripts/emoji-names.ts from emoji-datasource ${VERSION}. Don't edit it by hand.

/** Each short name's emoji, as \`:tada:\` names 🎉. */
export const EMOJI: Readonly<Record<string, string>> = {
${names.map(({ name, text }) => `  ${JSON.stringify(name)}: ${JSON.stringify(text)},`).join("\n")}
};

/**
 * The emoji that take a skin tone, as \`:+1::skin-tone-3:\` gives 👍🏼: 1 where it goes after the emoji's
 * first code point, in place of the variation selector after it, and 2 where it goes after its last as
 * well, as two people take one tone.
 */
export const TONED: Readonly<Record<string, 1 | 2>> = {
${toneNames.map(({ name, rule }) => `  ${JSON.stringify(name)}: ${rule},`).join("\n")}
};
`;

const outputPath = fileURLToPath(new URL("../src/bots/emoji-names.ts", import.meta.url));
writeFileSync(outputPath, output);
console.log(`Wrote ${names.length} short names, ${toneNames.length} of them with skin tones, to ${outputPath}`);

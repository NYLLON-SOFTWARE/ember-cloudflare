import path from "node:path";
import { LAYERS, type TestReference } from "./scan";
import { AREAS, type Area, type FeatureSpec, type Origin, type Status } from "./spec";

// Renders PARITY.md from the inventory and the tests that name its features.

/** The commits the inventory was taken from. Bump these when re-surveying ember-rust. */
export const EMBER_RUST_COMMIT = "cfeb4c289f9ab3042248777f29a103294ff3de87";
export const CAMPFIRE_COMMIT = "90b330024dec3e757c79b6a7e6568f93da8e3148";

const EMBER_RUST = `https://github.com/NYLLON-SOFTWARE/ember-rust/blob/${EMBER_RUST_COMMIT}/`;
const CAMPFIRE = `https://github.com/basecamp/once-campfire/blob/${CAMPFIRE_COMMIT}/`;

const STATUS_ICON: Record<Status, string> = { ported: "✅", partial: "🟡", todo: "⬜", "n/a": "➖" };
const STATUS_LABEL: Record<Status, string> = {
  ported: "✅ Ported",
  partial: "🟡 Partial",
  todo: "⬜ Not started",
  "n/a": "➖ Not applicable",
};
const ORIGIN_LABEL: Record<Origin, string> = { campfire: "Campfire", ember: "Ember", cloudflare: "This port" };

export const areaOf = (feature: FeatureSpec) => feature.id.slice(0, feature.id.indexOf(".")) as Area;

/** GitHub's anchor for a heading. */
const anchor = (heading: string) => heading.toLowerCase().replace(/[^a-z0-9 -]/g, "").replace(/ /g, "-");

/** Keeps `<` and `>` in prose from being read as HTML, leaving `code spans` alone. */
const prose = (text: string) =>
  text
    .split(/(`[^`]*`)/)
    .map((part) => (part.startsWith("`") ? part : part.replace(/</g, "&lt;").replace(/>/g, "&gt;")))
    .join("");

const cell = (text: string) => prose(text).replace(/\|/g, "\\|");

function sourceLink(source: string): string {
  const url = source.startsWith("reference/") ? CAMPFIRE + source.slice("reference/".length) : EMBER_RUST + source;
  return `[\`${source}\`](${url})`;
}

function testsCell(references: readonly TestReference[] = []): string {
  return LAYERS.flatMap(({ name }) => {
    const files = [...new Set(references.filter((r) => r.layer === name).map((r) => r.file))];
    if (files.length === 0) return [];
    const links = files.map((file) => `[${path.posix.basename(file).replace(/\.(test|spec)\.tsx?$/, "")}](${file})`);
    return [`${name}: ${links.join(", ")}`];
  }).join("<br>");
}

function counts(features: readonly FeatureSpec[]) {
  const count = (status: Status) => features.filter((f) => f.status === status).length;
  return { ported: count("ported"), partial: count("partial"), todo: count("todo"), na: count("n/a"), total: features.length };
}

export function renderChecklist(features: readonly FeatureSpec[], references: ReadonlyMap<string, readonly TestReference[]>): string {
  const areas = (Object.keys(AREAS) as Area[])
    .map((area) => ({ area, heading: AREAS[area], items: features.filter((f) => areaOf(f) === area) }))
    .filter(({ items }) => items.length > 0);
  const all = counts(features);

  const out = [
    "<!-- Generated by packages/parity. Edit packages/parity/src/features.ts or the tests, then run `pnpm parity`. -->",
    "",
    "# Parity with ember-rust",
    "",
    "Every feature of [ember-rust](https://github.com/NYLLON-SOFTWARE/ember-rust), whether this port has it yet, and the",
    "tests here that check it. The behaviors under each area are what a port has to do to match ember-rust, taken from its",
    `source at [\`${EMBER_RUST_COMMIT.slice(0, 7)}\`](https://github.com/NYLLON-SOFTWARE/ember-rust/tree/${EMBER_RUST_COMMIT})`,
    `and the Campfire app it pins at [\`${CAMPFIRE_COMMIT.slice(0, 7)}\`](https://github.com/basecamp/once-campfire/tree/${CAMPFIRE_COMMIT}).`,
    "",
    "`pnpm test` fails when a ported or partial feature has no test, when a test names a feature that isn't listed here,",
    "or when this file is out of date. Tests name the feature they cover with `describe(feature(\"messages.edit\"), ...)`.",
    "",
    "**Status:** ✅ ported · 🟡 partial (the note says what's missing) · ⬜ not started · ➖ not applicable to this port<br>",
    "**Origin:** Campfire (inherited by ember-rust) · Ember (added or changed by Ember) · This port (Cloudflare only)",
    "",
    `**Overall:** ${all.ported} ported and ${all.partial} partial of ${all.total} features; ${all.todo} not started, ${all.na} not applicable.`,
    "",
    "| Area | ✅ | 🟡 | ⬜ | ➖ | Features |",
    "|---|--:|--:|--:|--:|--:|",
    ...areas.map(({ heading, items }) => {
      const c = counts(items);
      return `| [${heading}](#${anchor(heading)}) | ${c.ported} | ${c.partial} | ${c.todo} | ${c.na} | ${c.total} |`;
    }),
    `| **Total** | **${all.ported}** | **${all.partial}** | **${all.todo}** | **${all.na}** | **${all.total}** |`,
  ];

  for (const { heading, items } of areas) {
    out.push("", `## ${heading}`, "", "| Feature | ID | Origin | Status | Tests |", "|---|---|---|---|---|");
    for (const f of items) {
      out.push(`| ${cell(f.title)} | \`${f.id}\` | ${ORIGIN_LABEL[f.origin]} | ${STATUS_LABEL[f.status]} | ${testsCell(references.get(f.id))} |`);
    }
    out.push("", "<details>", "<summary>Behaviors and sources</summary>", "");
    for (const f of items) {
      out.push(`**${prose(f.title)}** (\`${f.id}\`) ${STATUS_ICON[f.status]}`, "");
      out.push(...f.behaviors.map((b) => `- ${prose(b)}`), "");
      if (f.notes) out.push(`Note: ${prose(f.notes)}`, "");
      if (f.sources.length > 0) out.push(`Sources: ${f.sources.map(sourceLink).join(" · ")}`, "");
      if (f.upstreamTests?.length) out.push(`ember-rust tests: ${f.upstreamTests.map(sourceLink).join(" · ")}`, "");
    }
    out.push("</details>");
  }

  return out.join("\n") + "\n";
}
